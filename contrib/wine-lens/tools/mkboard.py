"""Describe this machine's lens board to Wine.

Reads the board's USB descriptors from sysfs (nothing is sent to the board) and writes
  board.h      the descriptors, compiled into a2ousb.sys
  device.reg   registry entries that present the board the way Windows would: a composite USB device with a
               serial-port function on COM3, below a root hub owned by a2ousb, plus the settings the shims need

usage: mkboard.py <tty device, e.g. /dev/odyssey-lens> <board.h> <device.reg>
"""
import os, sys

VID, PID = "354b", "0116"
PREFIX = "6&a2f0e15&0"            # ParentIdPrefix: any value; children are named "<prefix>&0000"
HUB = r"USB\ROOT_HUB30\4&a2f0e15&0&0"
USB_CLASS = "{36fc9e60-c465-11cf-8056-444553540000}"
COMPORT = "{86e0d1e0-8089-11d0-9ce4-08003e301f73}"
HCD = "{3abf6f2d-71c4-462a-8a92-1e6861e6af27}"

def usb_device(tty):
    path = os.path.realpath(os.path.join("/sys/class/tty", os.path.basename(os.path.realpath(tty)), "device"))
    while path != "/":
        if os.path.exists(os.path.join(path, "idVendor")): return path
        path = os.path.dirname(path)
    sys.exit(f"{tty} is not a USB serial device")

def read(dev, name): return open(os.path.join(dev, name)).read().strip()
def multi_sz(*items): return ",".join("%02x" % b for b in "".join(i + "\0" for i in items).encode() + b"\0")
def esc(s): return s.replace("\\", "\\\\")
def c_bytes(b): return "{" + ",".join(str(x) for x in b) + "}"

def main(tty, header, reg):
    dev = usb_device(tty)
    if (read(dev, "idVendor"), read(dev, "idProduct")) != (VID, PID):
        sys.exit(f"{tty} is not the Odyssey 3D lens board ({VID}:{PID})")
    raw = open(os.path.join(dev, "descriptors"), "rb").read()
    device, config = raw[:18], raw[18:18 + int.from_bytes(raw[20:22], "little")]
    serial = read(dev, "serial")
    strings = [read(dev, "manufacturer"), read(dev, "product"), serial]
    # They go into C string literals and into the registry file, the serial number into a key's name: nothing
    # that could end either early (a device can put any character into its strings).
    if any(not s.isprintable() or any(c in s for c in '"\\[]') for s in strings):
        sys.exit("unexpected characters in the board's strings")
    with open(header, "w") as f:
        f.write("/* Generated by mkboard.py from sysfs: this lens board's own USB descriptors. */\n")
        f.write(f"static const unsigned char board_device_desc[{len(device)}] = {c_bytes(device)};\n")
        f.write(f"static const unsigned char board_config_desc[{len(config)}] = {c_bytes(config)};\n")
        f.write("static const WCHAR *const board_strings[4] = {0, " + ", ".join(f'L"{s}"' for s in strings) + "};\n")
        f.write(f"static const unsigned char board_string_index[3] = {c_bytes(device[14:17])};\n")
        f.write(f"#define BOARD_ADDRESS {int(read(dev, 'devnum'))}\n")

    up = f"VID_{VID.upper()}&PID_{PID.upper()}"
    rev = "%02X%02X" % (device[13], device[12])
    parent, child = f"USB\\{up}\\{serial}", f"USB\\{up}&MI_00\\{PREFIX}&0000"
    enum = r"HKEY_LOCAL_MACHINE\System\CurrentControlSet\Enum"
    classes = r"HKEY_LOCAL_MACHINE\System\CurrentControlSet\Control\DeviceClasses"
    link = "##?#" + child.replace("\\", "#") + "#" + COMPORT
    hcd_link = f"##?#ROOT#A2OUSB#0000#{HCD}"
    winrt = r"HKEY_LOCAL_MACHINE\Software\Microsoft\WindowsRuntime\ActivatableClassId"
    # (made here and not inside the f-strings below: before Python 3.12 an f-string's expressions cannot hold
    # a backslash, and the whole file then fails to compile)
    hardware_ids = multi_sz(f"USB\\{up}&REV_{rev}", f"USB\\{up}")
    composite_ids = multi_sz("USB\\DevClass_00&SubClass_00&Prot_00", "USB\\DevClass_00", "USB\\COMPOSITE")
    serial_ids = multi_sz("USB\\Class_02&SubClass_02&Prot_01", "USB\\Class_02&SubClass_02", "USB\\Class_02")
    lines = ["REGEDIT4", "",
        r"[HKEY_LOCAL_MACHINE\SOFTWARE\Dimenco\Simulated Reality]", r'@="C:\\Program Files\\LeiaSR\\Platform"',
        '"Server IP"="localhost"', '"DuplicatedDevices"=dword:00000000', '"NonNativeResolution"=dword:00000000', "",
        r"[HKEY_LOCAL_MACHINE\Software\Wine\Ports]", f'"COM3"="{tty}"', "",
        r"[HKEY_CURRENT_USER\Software\Wine\DllOverrides]",
        '"cfgmgr32"="native,builtin"', '"dxva2"="native,builtin"', '"wtsapi32"="native,builtin"', ""]
    for cls in ("Windows.UI.Notifications.ToastNotification", "Windows.UI.Notifications.ToastNotificationManager",
                "Windows.Data.Xml.Dom.XmlDocument"):
        lines += [f"[{winrt}\\{cls}]", r'"DllPath"="C:\\windows\\system32\\a2otoast.dll"',
                  '"ActivationType"=dword:00000000', '"Threading"=dword:00000000', '"TrustLevel"=dword:00000000', ""]
    lines += [
        # the information-only host controller and root hub (a2ousb.sys)
        r"[HKEY_LOCAL_MACHINE\System\CurrentControlSet\Services\a2ousb]", '"Type"=dword:00000001',
        '"Start"=dword:00000003', '"ErrorControl"=dword:00000001',
        r'"ImagePath"="C:\\windows\\system32\\drivers\\a2ousb.sys"',
        '"DisplayName"="Any2Odyssey USB information driver"', "",
        f"[{enum}\\ROOT\\A2OUSB\\0000]", '"DeviceDesc"="USB Host Controller (information only)"', '"Class"="USB"',
        f'"ClassGUID"="{USB_CLASS}"', '"Service"="a2ousb"', f'"Driver"="{USB_CLASS}\\\\0000"', "",
        f"[{classes}\\{HCD}\\{hcd_link}]", r'"DeviceInstance"="ROOT\\A2OUSB\\0000"', "",
        f"[{classes}\\{HCD}\\{hcd_link}\\#]", r'"SymbolicLink"="\\\\?\\A2OHcd0"', "",
        f"[{classes}\\{HCD}\\{hcd_link}\\#\\Control]", '"Linked"=dword:00000001', "",
        f"[{enum}\\{HUB}]", '"DeviceDesc"="USB Root Hub (USB 3.0)"', '"Class"="USB"', f'"ClassGUID"="{USB_CLASS}"',
        '"Service"="a2ousb"', f'"Driver"="{USB_CLASS}\\\\0001"', r'"ParentDevice"="ROOT\\A2OUSB\\0000"', "",
        # the board: composite parent and its serial-port function
        f"[-{enum}\\{parent}]", "",
        f"[{enum}\\{parent}]", '"DeviceDesc"="USB Composite Device"', '"Mfg"="(Standard USB Host Controller)"',
        '"Service"="usbccgp"', '"Class"="USB"', f'"ClassGUID"="{USB_CLASS}"', '"Capabilities"=dword:00000014',
        '"ConfigFlags"=dword:00000000', f'"ParentIdPrefix"="{PREFIX}"',
        f'"HardwareID"=hex(7):{hardware_ids}',
        f'"Driver"="{USB_CLASS}\\\\0116"', '"Address"=dword:00000001',
        f'"CompatibleIDs"=hex(7):{composite_ids}',
        f'"ParentDevice"="{esc(HUB)}"', "",
        f"[{enum}\\{child}]", '"DeviceDesc"="USB Serial Device"', '"FriendlyName"="USB Serial Device (COM3)"',
        '"Mfg"="Microsoft"', '"Service"="usbser"', '"Class"="Ports"',
        '"ClassGUID"="{4d36e978-e325-11ce-bfc1-08002be10318}"', '"Capabilities"=dword:00000000',
        '"ConfigFlags"=dword:00000000', '"Address"=dword:00000001',
        f'"CompatibleIDs"=hex(7):{serial_ids}', "",
        f"[{enum}\\{child}\\Device Parameters]", '"PortName"="COM3"', "",
        f"[{classes}\\{COMPORT}\\{link}]", f'"DeviceInstance"="{esc(child)}"', "",
        f"[{classes}\\{COMPORT}\\{link}\\#]", f'"SymbolicLink"="\\\\\\\\?\\\\{child.replace(chr(92), "#")}#{COMPORT}"', "",
        f"[{classes}\\{COMPORT}\\{link}\\#\\Control]", '"Linked"=dword:00000001', ""]
    open(reg, "w").write("\r\n".join(lines))

main(*sys.argv[1:4])
